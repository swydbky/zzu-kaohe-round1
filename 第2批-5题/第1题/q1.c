#include <stdio.h>


void transpose(int (*arr)[3])
/* 形参int(*arr)[3]是“指向含3个int的数组”的指针，也就是二维数组的行指针。

 这里没有定义矩阵有多少行，行数在下面的main里才确定为3
 矩阵剩下的部分是这个函数拿到第0行的地址之后通过加i，j算出剩下的项所在的地址然后取过来里面的数的

 另外，int arr[2][3]意为定义一个含2个元素的数组，每个元素是一个int[3]（含3个int的小数组）*/
{
    int i = 0;
    int j = 0;

    /* 只遍历主对角线右上方的元素，把arr[i][j]和arr[j][i]交换；
       如果把3x3全部遍历一遍，会交换两次，矩阵就又转回去了。 */
    for (i = 0; i < 3; i++)    /* 这里函数其实不知道有3行，这个3是人为限制的 */
    {
        for (j = i + 1; j < 3; j++)
        {
            int t = *(*(arr + i) + j);
            /* arr+i得到这行的地址，左边打个星号取出里面的东西（一行），退化为其中第一个元素的地址
            从第0个元素向后跳j个，取他的地址，左边加个*进去取到这个数 */

            /* 左边加个*叫做解引用，意思是取出他右边的东西里的值 */

            /* *(*(arr+i)+j)就是arr[i][j]（取第i行j列的数）的另一种写法，本题要求用指针，故写前一种 */
            *(*(arr + i) + j) = *(*(arr + j) + i);
            *(*(arr + j) + i) = t;    /* 交换 */
        }
    }
}

int main(void)
{
    int a[3][3];
    int i = 0;
    int j = 0;

    for (i = 0; i < 3; i++)    /* 两层循环把9个元素输入到3*3的数组里 */
    {
        for (j = 0; j < 3; j++)
        {
            scanf("%d", &a[i][j]);
        }
    }

    transpose(a);
    /* 数组名出现在表达式里时，会自动被编译器替换成指向它第一个元素的指针，
    数组名a在这里自动退化成“指向第0行的指针”，也就是int(*)[3]
    []的优先级比*高，所以加小括号 */
    for (i = 0; i < 3; i++)
    {
        for (j = 0; j < 3; j++)
        {
            if (j > 0)
            {
                printf(" ");
            }
            printf("%d", a[i][j]);
        }
        printf("\n");    /* 数字之间用空格隔开，行末不加多余空格 */
    }

    return 0;
}
